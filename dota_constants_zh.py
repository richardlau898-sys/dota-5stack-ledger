def sanitize_mixed_english_text(text: str) -> str:
    """自动检测并替换文本中混杂的英文技能名、装备 key 或下划线标识符为纯中文"""
    if not text or not isinstance(text, str):
        return text
    out = text
    # 1. 替换已知的英文词组技能名
    for eng_phrase, zh_val in LEGACY_ENGLISH_TO_ZH_MAP.items():
        if eng_phrase in out:
            out = out.replace(eng_phrase, zh_val)
    # 2. 替换 ABILITIES_ZH 与 ITEMS_ZH 中的 snake_case key
    if "_" in out or any(k in out for k in ("tpscroll", "famango", "clarity", "tango", "flask", "dagon")):
        for ak, azh in ABILITIES_ZH.items():
            if ak in out:
                out = out.replace(ak, azh)
        for ik, izh in ITEMS_ZH.items():
            if len(ik) >= 4 and ik in out:
                out = out.replace(ik, izh)
    return out


def sanitize_report_mixed_english(obj: Any, parent_key: str = "") -> Any:
    """递归清洗整份报告 JSON 中的所有面向用户的文本字段，确保 0 英文下划线技能/道具外泄"""
    skip_keys = {
        "key",
        "ability_key",
        "side",
        "winner_side",
        "user_team_side",
        "focus_side",
        "grade",
        "severity",
        "type",
        "posture",
        "territory",
        "img",
        "hero_img",
        "hero_icon",
        "icon",
        "personaname",
        "caster_player",
        "victim_player",
        "rubick_player",
        "killer_player",
        "own_player",
        "opp_player",
        "planter_player",
        "breaker_player",
        "main_name",
    }
    if isinstance(obj, str):
        if parent_key in skip_keys or obj.startswith("http") or obj.startswith("npc_"):
            return obj
        return sanitize_mixed_english_text(obj)
    if isinstance(obj, list):
        return [sanitize_report_mixed_english(v, parent_key) for v in obj]
    if isinstance(obj, dict):
        return {k: sanitize_report_mixed_english(v, k) for k, v in obj.items()}
    return obj
