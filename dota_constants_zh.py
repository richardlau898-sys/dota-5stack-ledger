def get_item_zh(item_key: str, fallback_dname: str = "") -> str:
    """将任何装备/散件/消耗品/中立道具/附魔词条 key 转为 100% 纯中文名称"""
    if not item_key:
        return ""
    k = str(item_key).strip()
    if k in ITEMS_ZH:
        return ITEMS_ZH[k]
    if k.lower() in ITEMS_ZH:
        return ITEMS_ZH[k.lower()]
    if k.startswith("recipe_"):
        base_k = k[len("recipe_"):]
        base_zh = ITEMS_ZH.get(base_k) or ITEMS_ZH.get(base_k.lower()) or "装备"
        return f"{base_zh}合成卷轴"
    if k.startswith("dagon_"):
        lvl = k.split("_")[-1]
        return f"达贡之神力({lvl}级红杖)"
    if k.startswith("necronomicon_"):
        lvl = k.split("_")[-1]
        return f"死灵书({lvl}级)"
    if k.startswith("enhancement_"):
        return "中立附魔词条"
    return "战术道具"


