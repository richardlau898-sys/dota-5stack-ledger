def get_ability_zh(ability_key: str) -> str:
    if ability_key in ABILITIES_ZH:
        return ABILITIES_ZH[ability_key]
    # 过滤掉通用机关如双生门、观察者灯塔
    if ability_key in ("twin_gate_portal_warp", "ability_lamp_use", "ability_capture", "plus_high_five", "default_attack"):
        return ""
    # 把下划线转成简短可读形式
    parts = ability_key.split("_")
    if len(parts) > 2:
        return " ".join(p.capitalize() for p in parts[-2:])
    return ability_key


