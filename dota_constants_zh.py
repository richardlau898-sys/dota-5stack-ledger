def get_rank_name(rank_tier: int) -> str:
    if not rank_tier:
        return "未知段位"
    medal = rank_tier // 10
    stars = rank_tier % 10
    base = RANK_TIER_ZH.get(medal, f"段位{medal}")
    if medal == 8 or stars == 0:
        return base
    return f"{base}[{stars}星]"


