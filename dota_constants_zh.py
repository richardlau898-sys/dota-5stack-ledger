def get_hero_name(hero_id: int) -> str:
    if hero_id in HEROES_ZH:
        zh, short, _ = HEROES_ZH[hero_id]
        return zh if zh == short else f"{zh}({short})"
    return f"英雄#{hero_id}"


def get_hero_default_pos(hero_id: int) -> float:
    if hero_id in HEROES_ZH:
        return HEROES_ZH[hero_id][2]
    return 3.0


def get_rank_name(rank_tier: int) -> str:
    if not rank_tier:
        return "未知段位"
    medal = rank_tier // 10
    stars = rank_tier % 10
    base = RANK_TIER_ZH.get(medal, f"段位{medal}")
    if medal == 8 or stars == 0:
        return base
    return f"{base}[{stars}星]"


